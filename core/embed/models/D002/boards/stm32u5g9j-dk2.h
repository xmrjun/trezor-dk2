#ifndef STM32U5G9J_DK2_H_
#define STM32U5G9J_DK2_H_

// STM32U5G9J-DK2: 5" 800x480 RGB parallel LCD (RK050HR18) driven directly by
// LTDC (no DSI), GT911 capacitive touch on I2C2.

#define VDD_1V8 1

// The UI is enlarged by DISPLAY_UPSCALE_NUM / DISPLAY_UPSCALE_DEN on the panel
// (nearest neighbour); used by both the display panel and the touch driver.
#define DISPLAY_UPSCALE_NUM 5
#define DISPLAY_UPSCALE_DEN 4

// LCD_ON (display enable)
#define DISPLAY_ENABLE_PIN GPIO_PIN_4
#define DISPLAY_ENABLE_PORT GPIOE
#define DISPLAY_ENABLE_CLK_ENA __HAL_RCC_GPIOE_CLK_ENABLE

#define BACKLIGHT_PIN_PIN GPIO_PIN_6
#define BACKLIGHT_PIN_PORT GPIOE
#define BACKLIGHT_PIN_CLK_ENABLE() __HAL_RCC_GPIOE_CLK_ENABLE()

#define I2C_COUNT 1
#define I2C_INSTANCE_0 I2C2
#define I2C_INSTANCE_0_CLK_EN __HAL_RCC_I2C2_CLK_ENABLE
#define I2C_INSTANCE_0_CLK_DIS __HAL_RCC_I2C2_CLK_DISABLE
#define I2C_INSTANCE_0_PIN_AF GPIO_AF4_I2C2
#define I2C_INSTANCE_0_SDA_PORT GPIOF
#define I2C_INSTANCE_0_SDA_PIN GPIO_PIN_0
#define I2C_INSTANCE_0_SDA_CLK_EN __HAL_RCC_GPIOF_CLK_ENABLE
#define I2C_INSTANCE_0_SCL_PORT GPIOF
#define I2C_INSTANCE_0_SCL_PIN GPIO_PIN_1
#define I2C_INSTANCE_0_SCL_CLK_EN __HAL_RCC_GPIOF_CLK_ENABLE
#define I2C_INSTANCE_0_RESET_REG &RCC->APB1RSTR1
#define I2C_INSTANCE_0_RESET_BIT RCC_APB1RSTR1_I2C2RST
#define I2C_INSTANCE_0_EV_IRQHandler I2C2_EV_IRQHandler
#define I2C_INSTANCE_0_ER_IRQHandler I2C2_ER_IRQHandler
#define I2C_INSTANCE_0_EV_IRQn I2C2_EV_IRQn
#define I2C_INSTANCE_0_ER_IRQn I2C2_ER_IRQn
#define I2C_INSTANCE_0_GUARD_TIME 0

#define TOUCH_I2C_INSTANCE 0

// GT911 control lines (RST is shared with the red user LED LD2)
#define TOUCH_RST_PORT GPIOD
#define TOUCH_RST_PIN GPIO_PIN_2
#define TOUCH_RST_CLK_ENA __HAL_RCC_GPIOD_CLK_ENABLE
#define TOUCH_INT_PORT GPIOE
#define TOUCH_INT_PIN GPIO_PIN_5
#define TOUCH_INT_CLK_ENA __HAL_RCC_GPIOE_CLK_ENABLE

#endif  // STM32U5G9J_DK2_H_
