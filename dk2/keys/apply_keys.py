#!/usr/bin/env python3
"""Put the public halves of our key set into the build, and make our vendor header.

  XW_KEYS=<keys.json> .venv/bin/python dk2/keys/apply_keys.py

Writes (all git-ignored, regenerated on every build by dk2/build.sh):
  core/embed/sec/image/inc/sec/xw_keys.h            root, bootloader and secmon keys
  core/embed/rust/src/translations/xw_public_keys.rs  language blob keys
  dk2/keys/build/vendorheader_xw_signed.bin         vendor header with our firmware
                                                    keys, signed with our bootloader keys
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
KEYS_H = ROOT / "core/embed/sec/image/inc/sec/xw_keys.h"
KEYS_RS = ROOT / "core/embed/rust/src/translations/xw_public_keys.rs"
OUT = HERE / "build"
VH_SPEC = HERE / "vendor_xw.json"
VH_TOIF = ROOT / "core/embed/models/D002/vendorheader/vendor_dev_DO_NOT_SIGN.toif"
VH_BIN = OUT / "vendorheader_xw_signed.bin"


def c_keys(name: str, keys: list[dict]) -> str:
    lines = [f'  (const uint8_t *)"{"".join(f"\\x{b:02x}" for b in bytes.fromhex(k["pub"]))}",'
             for k in keys]
    return f"#define {name} \\\n" + " \\\n".join(lines) + "\n"


def main() -> None:
    path = os.environ.get("XW_KEYS")
    if not path:
        sys.exit("XW_KEYS is not set")
    keys = json.loads(Path(path).read_text())
    assert len(keys["root_slh_dsa"]) == len(keys["root_ed25519"]) <= 3
    for role in ("bootloader", "secmon", "vendor", "translations"):
        assert len(keys[role]) == 3, role

    KEYS_H.write_text(
        "#pragma once\n\n"
        f"// Generated by dk2/keys/apply_keys.py from key set \"{keys['name']}\". Do not edit.\n\n"
        "// clang-format off\n"
        + c_keys("XW_ROOT_SLH_DSA_KEYS", keys["root_slh_dsa"]) + "\n"
        + c_keys("XW_ROOT_ED25519_KEYS", keys["root_ed25519"]) + "\n"
        + c_keys("XW_BOOTLOADER_KEYS", keys["bootloader"]) + "\n"
        + c_keys("XW_SECMON_KEYS", keys["secmon"])
        + "// clang-format on\n"
    )
    rs_keys = "".join(
        f'    *b"{"".join(f"\\x{b:02x}" for b in bytes.fromhex(k["pub"]))}",\n'
        for k in keys["translations"]
    )
    KEYS_RS.write_text(
        f"// Generated by dk2/keys/apply_keys.py from key set \"{keys['name']}\". Do not edit.\n"
        "pub const PUBLIC_KEYS_DEVEL: [ed25519::PublicKey; 3] = [\n" + rs_keys + "];\n"
    )

    # vendor header: our spec with our firmware keys, then signed with our bootloader keys
    OUT.mkdir(exist_ok=True)
    spec = json.loads(VH_SPEC.read_text())
    spec["pubkeys"] = [k["pub"] for k in keys["vendor"]]
    spec_out = OUT / "vendor_xw.json"
    spec_out.write_text(json.dumps(spec, indent=4) + "\n")
    bindir = Path(sys.executable).parent
    subprocess.run([sys.executable, ROOT / "core/tools/build_vendorheader", "-q",
                    "-i", VH_TOIF, "-o", VH_BIN, spec_out], check=True)
    subprocess.run([bindir / "headertool", "-q", "-D", VH_BIN], check=True)
    print(f"keys \"{keys['name']}\" applied: {KEYS_H.name}, {KEYS_RS.name}, {VH_BIN.name}")


if __name__ == "__main__":
    main()
